/**
 * 调休上班日（要上班但仍在节假日安排内）。
 *
 * 这些日期**不参与**峰谷计算（见文件头说明），单独列出来是为了：
 *   · 以后如果要显示"今天虽然是周末但要上班"，有数据可用
 *   · 排查时能一眼看出"为什么这天算谷时"
 */
export const BUILTIN_MAKEUP_WORKDAYS = Object.freeze({
  2026: Object.freeze([
    '20260104', // 元旦后补班（周日）
    '20260214', // 春节前补班（周六）
    '20260228', // 春节后补班（周六）
    '20260509', // 劳动节后补班（周六）
    '20260920', // 国庆前补班（周日）
    '20261010', // 国庆后补班（周六）
  ]),
})

/**
 * 取某年的内置节假日。
 * @param {number} year
 * @returns {string[]} 没有这一年就返回空数组
 */
export function builtinHolidaysFor(year) {
  const list = BUILTIN_HOLIDAYS[String(year)]
  return Array.isArray(list) ? list.slice() : []
}

/**
 * 内置数据覆盖了哪些年份
 * @returns {number[]}
 */
export function builtinYears() {
  return Object.keys(BUILTIN_HOLIDAYS).map(Number).sort()
}
